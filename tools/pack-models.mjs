// Blender exports (art-src/models/*.glb, built by art-src/blender/toys.py) → assets/models.js, a classic script
// setting window.__PB_MODELS = {name: base64 GLB}. The game parses them with GLTFLoader.parse (file:// safe).
//   node tools/pack-models.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(GAME, 'art-src', 'models');
const out = {};
for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.glb')).sort()) out[f.replace(/\.glb$/, '')] = fs.readFileSync(path.join(dir, f)).toString('base64');
fs.writeFileSync(path.join(GAME, 'assets', 'models.js'), `/* GENERATED by tools/pack-models.mjs from art-src/models/*.glb (art-src/blender/toys.py). */\nwindow.__PB_MODELS = ${JSON.stringify(out)};\n`);
console.log('assets/models.js:', Object.keys(out).length, 'models,', (fs.statSync(path.join(GAME, 'assets', 'models.js')).size / 1024).toFixed(0), 'KB');
