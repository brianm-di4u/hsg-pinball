#!/usr/bin/env node
// Packs the Codex paintings (art-src/art.json → assets/*.webp through the shared art-pack tool, adapted from
// hsg-property-game tools/build-art.mjs), then writes assets/art.js: a classic script setting window.__PB_ART to
// data URLs. WebGL refuses image files under file:// (tainted canvas), so the game only ever loads data URLs.
//   node tools/build-art.mjs [--only a,b]
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
execFileSync(process.execPath, [path.join(GAME, 'shared', 'test-harness', 'art-pack.mjs'), '.', ...process.argv.slice(2)], { cwd: GAME, stdio: 'inherit' });
const man = JSON.parse(fs.readFileSync(path.join(GAME, 'assets', 'manifest.json'), 'utf8'));
const names = Object.keys(man).filter((n) => fs.existsSync(path.join(GAME, 'assets', n + '.webp'))).sort();
const data = Object.fromEntries(names.map((n) => [n, 'data:image/webp;base64,' + fs.readFileSync(path.join(GAME, 'assets', n + '.webp')).toString('base64')]));
fs.writeFileSync(path.join(GAME, 'assets', 'art.js'), `/* GENERATED by tools/build-art.mjs from art-src/art.json: Codex paintings as data URLs (see art-src/PROMPTS.md). */\nwindow.__PB_ART = ${JSON.stringify(data)};\n`);
const kb = fs.statSync(path.join(GAME, 'assets', 'art.js')).size / 1024;
console.log(`assets/art.js: ${names.length} images, ${kb.toFixed(0)} KB`);
